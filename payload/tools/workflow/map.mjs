#!/usr/bin/env node
// Writes the file map (docs/MAP.md): one line per source file from its opening comment and imports.
//   node tools/workflow/map.mjs           write it     node tools/workflow/map.mjs --check   fail if it is out of date
//   node tools/workflow/map.mjs --find <words>   print only the map lines whose description has every word;  --uses <file>   the lines that import that file (read the map, write nothing)
// Settings: `map` in workflow.config.json ({ out, folders }).
import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { buildGraph } from './lib/graph.mjs';
import { renderMap, sameMap, findInMap, usesInMap } from './lib/map.mjs';
import { matchesAny } from './lib/glob.mjs';

const root = execFileSync('git', ['rev-parse', '--show-toplevel'], { encoding: 'utf8' }).trim();
process.chdir(root);
const config = JSON.parse(readFileSync('workflow.config.json', 'utf8'));
const findAt = process.argv.indexOf('--find'), usesAt = process.argv.indexOf('--uses');
if (findAt >= 0 || usesAt >= 0) {
  const at = findAt >= 0 ? findAt : usesAt;
  const words = process.argv.slice(at + 1).filter((w) => !w.startsWith('--'));
  const text = existsSync(config.map.out) ? readFileSync(config.map.out, 'utf8') : '';
  const { lines, more } = !words.length ? { lines: [], more: 0 } : findAt >= 0 ? findInMap(text, words, 25) : usesInMap(text, words[0], 25);
  if (!lines.length) { console.log('map: nothing matches ' + words.join(' ')); process.exit(1); }
  const tail = more ? ['(+' + more + ' more: use a narrower word)'] : [];
  console.log([...lines, ...tail].join('\n'));
  process.exit(0);
}
const all = execFileSync('git', ['ls-files', '--cached', '--others', '--exclude-standard'], { encoding: 'utf8', maxBuffer: 64 << 20 })
  .split('\n').filter((f) => /\.(?:ts|tsx|mjs|js)$/.test(f) && existsSync(f) && !matchesAny(f, config.skipFiles));
const files = new Map(all.map((f) => [f, readFileSync(f, 'utf8')]));
const head = `# File map\n\nGenerated by \`npm run map\` (tools/workflow/map.mjs): do not edit. One line per file: its opening comment's\nfirst sentence, then \`→\` the project files it imports (same folder by name, others from \`src/\`).\n\n`;
const text = head + renderMap(buildGraph(files), config.map.folders);

if (process.argv.includes('--check')) {
  const now = existsSync(config.map.out) ? readFileSync(config.map.out, 'utf8').replace(/\r\n/g, '\n') : '';
  if (now !== text) { console.error(`${config.map.out} is out of date: run npm run map`); process.exit(1); }
  console.log('map: up to date');
} else {
  writeFileSync(config.map.out, text);
  console.log(`map: ${config.map.out} written (${text.split('\n').length} lines)`);
}
