#!/usr/bin/env node
// Writes the file map (docs/MAP.md): one line per source file from its opening comment and imports; the infra map
// (docs/run/INFRA-MAP.md, every resource in the OpenTofu and Kubernetes files) once there are any; and the generated blocks in the
// docs (`<!-- generated: layers -->`, see lib/docblocks.mjs). Nothing it writes may be edited by hand.
//   node tools/workflow/map.mjs           write it     node tools/workflow/map.mjs --check   fail if it is out of date
//   node tools/workflow/map.mjs --find <words>   print only the map lines whose description has every word (without their imports; --imports adds them);  --uses <file>   the lines that import that file (read the map, write nothing)
// Settings: `map` in workflow.config.json ({ out, folders }).
import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { buildGraph } from './lib/graph.mjs';
import { renderMap, sameMap, findInMap, usesInMap, withoutImports } from './lib/map.mjs';
import { matchesAny } from './lib/glob.mjs';
import { codeTest } from './lib/lang.mjs';
import { parseK8s, parseTf, renderInfraMap } from './lib/infra.mjs';
import { networkPolicy } from './lib/netpolicy.mjs';
import { blockMakers, fillBlocks, hasBlocks } from './lib/docblocks.mjs';
import { renderDocsIndex } from './lib/docsindex.mjs';

const root = execFileSync('git', ['rev-parse', '--show-toplevel'], { encoding: 'utf8' }).trim();
process.chdir(root);
const config = JSON.parse(readFileSync('workflow.config.json', 'utf8'));
const findAt = process.argv.indexOf('--find'), usesAt = process.argv.indexOf('--uses');
if (findAt >= 0 || usesAt >= 0) {
  const at = findAt >= 0 ? findAt : usesAt;
  const words = process.argv.slice(at + 1).filter((w) => !w.startsWith('--'));
  const text = existsSync(config.map.out) ? readFileSync(config.map.out, 'utf8') : '';
  const { lines, more } = !words.length ? { lines: [], more: 0 } : findAt >= 0 ? findInMap(text, words, 25) : usesInMap(text, words[0], 25);
  if (!lines.length) { console.log('map: nothing matches ' + words.join(' ')); process.exit(1); }
  const tail = more ? ['(+' + more + ' more: use a narrower word)'] : [];
  const shown = findAt >= 0 && !process.argv.includes('--imports') ? lines.map(withoutImports) : lines;
  console.log([...shown, ...tail].join('\n'));
  process.exit(0);
}
const all = execFileSync('git', ['ls-files', '--cached', '--others', '--exclude-standard'], { encoding: 'utf8', maxBuffer: 64 << 20 })
  .split('\n').filter((f) => codeTest(config)(f) && existsSync(f) && !matchesAny(f, config.skipFiles));
const files = new Map(all.map((f) => [f, readFileSync(f, 'utf8')]));
const head = `# File map\n\nGenerated by \`npm run map\` (tools/workflow/map.mjs): do not edit. One line per file: its opening comment's\nfirst sentence, then \`→\` the project files it imports (same folder by name, others from \`src/\`).\n\n`;
const text = head + renderMap(buildGraph(files), config.map.folders);

// every page this writes: the file map, the infra map (when there are infrastructure files), and the generated blocks in docs
const pages = [[config.map.out, text]];
const listed = execFileSync('git', ['ls-files', '--cached', '--others', '--exclude-standard'], { encoding: 'utf8', maxBuffer: 64 << 20 }).split('\n').filter((f) => f && existsSync(f));
const infraOut = config.map.infraOut ?? 'docs/run/INFRA-MAP.md';
const tf = listed.filter((f) => /\.(tf|tofu)$/.test(f));
const k8s = listed.filter((f) => matchesAny(f, config.map.k8s ?? ['k8s/**/*.yaml', 'k8s/**/*.yml', 'deploy/**/*.yaml', 'infra/**/*.yaml', 'charts/**/templates/*.yaml']));
if (tf.length || k8s.length || existsSync(infraOut)) {
  const resources = [...tf.flatMap((f) => parseTf(f, readFileSync(f, 'utf8'))), ...k8s.flatMap((f) => parseK8s(f, readFileSync(f, 'utf8')))];
  pages.push([infraOut, renderInfraMap(resources)]);
}
// the network policy every infrastructure tool reads, once there is an infra folder (lib/netpolicy.mjs)
const infraDir = config.map.infraDir ?? 'infra';
if (existsSync(infraDir)) pages.push([`${infraDir}/network.json`, networkPolicy(config)]);
const read = (f) => (existsSync(f) ? readFileSync(f, 'utf8') : '');
// the docs index: one page saying where every doc is, grouped (lib/docsindex.mjs); the kit's own guides are the ones .workflow-kit lists
// (the pages this same run writes count too, so the first run and the second give the same index)
const writing = new Map(pages.filter(([f]) => f.startsWith('docs/') && f.endsWith('.md')));
const docsListed = [...new Set([...listed.filter((f) => f.startsWith('docs/') && f.endsWith('.md')), ...writing.keys()])].filter((f) => f !== 'docs/README.md').sort();
if (docsListed.length) {
  const kitFiles = new Set(read('.workflow-kit').split('\n').map((l) => /^sha \S+ (.+)$/.exec(l)?.[1]).filter(Boolean));
  pages.push(['docs/README.md', renderDocsIndex(docsListed.map((path) => ({ path, text: writing.get(path) ?? read(path) })), kitFiles)]);
}
const makers = blockMakers({ config, toolVersions: read('.tool-versions'), envExample: read('.env.example') });
for (const f of listed.filter((x) => x.endsWith('.md') && matchesAny(x, config.docs?.include ?? ['docs/*.md', 'docs/*/*.md']))) {
  const was = readFileSync(f, 'utf8').replace(/\r\n/g, '\n');
  if (hasBlocks(was)) pages.push([f, fillBlocks(was, makers)]);
}

if (process.argv.includes('--check')) {
  const stale = pages.filter(([f, want]) => (existsSync(f) ? readFileSync(f, 'utf8').replace(/\r\n/g, '\n') : '') !== want).map(([f]) => f);
  if (stale.length) { console.error(`${stale.join(', ')} ${stale.length === 1 ? 'is' : 'are'} out of date (made from the code and the config): run npm run map`); process.exit(1); }
  console.log('map: up to date');
} else {
  for (const [f, want] of pages) if (read(f).replace(/\r\n/g, '\n') !== want) writeFileSync(f, want);
  console.log(`map: ${config.map.out} written (${text.split('\n').length} lines)${pages.length > 1 ? `, and ${pages.slice(1).map(([f]) => f).join(', ')}` : ''}`);
}
