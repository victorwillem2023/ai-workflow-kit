// The infra map (no I/O here): every resource the infrastructure files declare, as one generated page, so the picture of
// servers, networks, buckets, DNS records and firewall rules is never older than the code. Reads OpenTofu/Terraform
// (`resource "type" "name" { ... }`, `module "name" { source = ... }`) and Kubernetes manifests (`kind:` and `metadata.name`).

const ATTRS = ['name', 'location', 'region', 'zone', 'datacenter', 'server_type', 'instance_type', 'size', 'type', 'image', 'source'];

/** The body of the block that opens at `start` (the index of its `{`), by counting braces outside strings. */
function blockAt(text, start) {
  let depth = 0;
  let quote = false;
  for (let i = start; i < text.length; i++) {
    const c = text[i];
    if (quote) { if (c === '\\') i++; else if (c === '"') quote = false; continue; }
    if (c === '"') quote = true;
    else if (c === '#' || (c === '/' && text[i + 1] === '/')) { const nl = text.indexOf('\n', i); i = nl < 0 ? text.length : nl; }
    else if (c === '{') depth++;
    else if (c === '}' && --depth === 0) return text.slice(start + 1, i);
  }
  return text.slice(start + 1);
}

/** The top-level `key = "value"` lines of a block body (nested blocks left out). */
function topAttrs(body) {
  const out = {};
  let depth = 0;
  for (const line of body.split('\n')) {
    const m = depth === 0 ? /^\s*([a-z_]+)\s*=\s*"?([^"\n]*?)"?\s*$/.exec(line) : null;
    if (m && ATTRS.includes(m[1]) && !(m[1] in out)) out[m[1]] = m[2];
    depth += (line.match(/\{/g) ?? []).length - (line.match(/\}/g) ?? []).length;
  }
  return out;
}

/** The resources and modules of one OpenTofu/Terraform file: [{ file, kind, id, attrs }]. */
export function parseTf(file, text) {
  const src = String(text ?? '');
  const out = [];
  for (const m of src.matchAll(/^(resource|module)\s+"([^"]+)"(?:\s+"([^"]+)")?\s*\{/gm)) {
    const attrs = topAttrs(blockAt(src, m.index + m[0].length - 1));
    out.push(m[1] === 'module' ? { file, kind: 'module', id: m[2], attrs } : { file, kind: m[2], id: m[3], attrs });
  }
  return out;
}

/** The objects of one Kubernetes manifest file (several documents split by ---): [{ file, kind, id, attrs }]. */
export function parseK8s(file, text) {
  const out = [];
  for (const doc of String(text ?? '').split(/^---\s*$/m)) {
    const kind = /^kind:\s*(\S+)/m.exec(doc)?.[1];
    if (!kind || !/^apiVersion:/m.test(doc)) continue;
    const name = /^metadata:\s*\n(?:\s+.*\n)*?\s+name:\s*["']?([^"'\s]+)/m.exec(doc)?.[1] ?? '?';
    const ns = /^metadata:\s*\n(?:\s+.*\n)*?\s+namespace:\s*["']?([^"'\s]+)/m.exec(doc)?.[1];
    const image = /^[\s-]+image:\s*["']?([^"'\s]+)/m.exec(doc)?.[1];
    out.push({ file, kind, id: name, attrs: { ...(ns ? { namespace: ns } : {}), ...(image ? { image } : {}) } });
  }
  return out;
}

const cell = (s) => String(s ?? '').replace(/\|/g, '\\|');

/** The page: one table per folder (a folder is usually one environment or one stack). */
export function renderInfraMap(resources) {
  const head = '# Infra map\n\nGenerated by `npm run map` from the infrastructure files: do not edit. One row per resource the code declares;\n' +
    'what it is, its name, where it runs and how big. Why each part is there: `docs/INFRA.md` and the project\'s own docs.\n';
  if (!resources.length) return `${head}\nNo infrastructure files yet.\n`;
  const byFolder = new Map();
  for (const r of resources) {
    const dir = r.file.includes('/') ? r.file.slice(0, r.file.lastIndexOf('/')) : '.';
    if (!byFolder.has(dir)) byFolder.set(dir, []);
    byFolder.get(dir).push(r);
  }
  const parts = [head];
  for (const [dir, list] of [...byFolder].sort(([a], [b]) => a.localeCompare(b))) {
    parts.push(`\n## ${dir}\n\n| Kind | In code | Name | Where | Size or source |\n|---|---|---|---|---|`);
    for (const r of list.sort((a, b) => a.kind.localeCompare(b.kind) || a.id.localeCompare(b.id))) {
      const a = r.attrs;
      parts.push(`| ${cell(r.kind)} | \`${cell(r.id)}\` | ${cell(a.name ?? '')} | ${cell(a.location ?? a.region ?? a.zone ?? a.datacenter ?? a.namespace ?? '')} | ${cell(a.server_type ?? a.instance_type ?? a.size ?? a.image ?? a.source ?? a.type ?? '')} |`);
    }
  }
  return `${parts.join('\n')}\n`;
}
